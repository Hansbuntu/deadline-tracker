import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'
import { VitePWA } from 'vite-plugin-pwa'

// https://vite.dev/config/
export default defineConfig({
  plugins: [
    react(),

    // Makes the site installable (a PWA): writes the web app manifest and a
    // service worker that keeps the app's own files on the device.
    VitePWA({
      // A new version waits until you tap "Update", so it never reloads mid-typing.
      registerType: 'prompt',
      // The globPatterns below already cache every icon once; listing them again
      // here (or letting the plugin add the manifest icons) cached 7 files twice.
      includeManifestIcons: false,

      // The manifest: what the phone shows when you install the app.
      manifest: {
        id: '/',
        name: 'Deadlines: open calls and residencies',
        short_name: 'Deadlines',
        description: 'A personal tracker for art open calls, residencies and grants, with deadline alerts.',
        lang: 'en-GB',
        start_url: '/',
        scope: '/',
        display: 'standalone', // opens full-screen, without the browser's address bar
        background_color: '#fafafa', // splash screen while it opens
        theme_color: '#fafafa', // phone status bar
        categories: ['productivity'],
        icons: [
          { src: 'pwa-64x64.png', sizes: '64x64', type: 'image/png' },
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png' },
          { src: 'maskable-icon-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },

      // The service worker, generated by Workbox (Google's service worker toolkit).
      workbox: {
        // Keep the app's own files: page, code, styles, fonts and icons.
        globPatterns: ['**/*.{html,js,css,svg,png,ico,woff2}'],
        // Opening any page of the app while offline shows the app itself.
        navigateFallback: 'index.html',
        // ...except future API routes (phase 4), which must always reach the server.
        navigateFallbackDenylist: [/^\/api\//],
        cleanupOutdatedCaches: true,
        // Nothing from Supabase is cached: your list and sign-in are always live.
      },
    }),
  ],
})
